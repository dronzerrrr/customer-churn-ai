"""Fill the RESULTS and EXAMPLES blocks of README.md from the real artifacts.

Nothing is typed by hand: every number comes from artifacts/metrics.json,
reports/*.csv and the saved model. Re-run after retraining:
    python -m src.reporting.update_readme
"""
import json
import re
from datetime import datetime, timezone

import pandas as pd

from src.config import METADATA_PATH, METRICS_PATH, PROJECT_ROOT, REPORTS_DIR

README = PROJECT_ROOT / "README.md"


def replace_block(text: str, name: str, content: str) -> str:
    """Replace everything between <!-- NAME:START --> and <!-- NAME:END -->."""
    start, end = f"<!-- {name}:START -->", f"<!-- {name}:END -->"
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
    if not pattern.search(text):
        raise ValueError(f"README is missing the markers {start} ... {end}")
    return pattern.sub(lambda _: f"{start}\n{content.strip()}\n{end}", text, count=1)


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def results_markdown(metrics: dict, meta: dict, importance: pd.DataFrame | None = None) -> str:
    sizes = metrics["split_sizes"]
    test = metrics["test_metrics"]
    cm = test["confusion_matrix"]
    base = metrics["dummy_baseline_test"]
    versions = meta.get("versions", {})

    comp_rows = [[r["model"], f"{r['accuracy']:.3f}", f"{r['precision']:.3f}", f"{r['recall']:.3f}",
                  f"{r['f1']:.3f}", f"{r['roc_auc']:.3f}", f"{r['pr_auc']:.3f}"]
                 for r in metrics["validation_comparison"]]
    final_rows = [[k, f"{test[key]:.3f}"] for k, key in [
        ("Accuracy", "accuracy"), ("Precision", "precision"), ("Recall", "recall"),
        ("F1-score", "f1"), ("ROC-AUC", "roc_auc"), ("PR-AUC", "pr_auc")]]

    parts = [
        f"_Generated by `python -m src.reporting.update_readme` from `artifacts/metrics.json` "
        f"(trained {meta.get('trained_at_utc', 'unknown')}; Python {versions.get('python', '?')}, "
        f"scikit-learn {versions.get('sklearn', '?')}). Re-run training to reproduce._",
        "",
        f"**Data split** (stratified, seed {meta.get('random_state', 42)}): "
        f"{sizes['train']:,} train / {sizes['val']:,} validation / {sizes['test']:,} test. "
        f"Churn rate in training data: {metrics['train_churn_rate']:.1%}.",
        "",
        "**Model comparison on the validation set** (precision, recall and F1 at a 0.5 threshold "
        "so models compare fairly; the model was selected by PR-AUC):",
        "",
        md_table(["Model", "Accuracy", "Precision", "Recall", "F1", "ROC-AUC", "PR-AUC"], comp_rows),
        "",
        f"**Final model: {metrics['selected_model']}**, decision threshold "
        f"**{test['threshold']:.2f}** (chosen on validation data by maximising F"
        f"{meta.get('threshold_beta', 2):.0f}, which weights recall more than precision). "
        "The test set was used once, after selection:",
        "",
        md_table(["Metric (test set)", "Value"], final_rows),
        "",
        f"Confusion matrix on {sum(cm.values()):,} test customers: "
        f"{cm['tp']} churners caught, {cm['fn']} missed, {cm['fp']} false alarms, "
        f"{cm['tn']} correctly left alone.",
        "",
        f"**Why accuracy misleads:** a baseline that predicts \"nobody churns\" scores "
        f"{base['accuracy']:.1%} accuracy while catching {base['recall']:.0%} of churners. "
        f"The final model's accuracy ({test['accuracy']:.1%}) is lower on purpose: the threshold "
        "trades false alarms for catching more churners.",
    ]
    if importance is not None and not importance.empty:
        top = importance.head(8)
        rows = [[name, f"{r['mean_abs_shap']:.3f}",
                 f"{r['permutation_pr_auc_drop']:.3f}" if pd.notna(r["permutation_pr_auc_drop"]) else "-"]
                for name, r in top.iterrows()]
        parts += ["", "**Most influential features** (validation data). The two methods can rank "
                  "features differently because features are correlated:", "",
                  md_table(["Feature", "Mean absolute SHAP", "Permutation PR-AUC drop"], rows)]
    return "\n".join(parts)


EXAMPLE_PROFILES = {
    "Higher-risk profile": dict(
        gender="Female", SeniorCitizen=0, Partner="No", Dependents="No", tenure=5,
        PhoneService="Yes", MultipleLines="No", InternetService="Fiber optic",
        OnlineSecurity="No", OnlineBackup="No", DeviceProtection="No", TechSupport="No",
        StreamingTV="Yes", StreamingMovies="Yes", Contract="Month-to-month",
        PaperlessBilling="Yes", PaymentMethod="Electronic check", MonthlyCharges=95.5),
    "Lower-risk profile": dict(
        gender="Male", SeniorCitizen=0, Partner="Yes", Dependents="Yes", tenure=70,
        PhoneService="Yes", MultipleLines="No", InternetService="No",
        OnlineSecurity="No internet service", OnlineBackup="No internet service",
        DeviceProtection="No internet service", TechSupport="No internet service",
        StreamingTV="No internet service", StreamingMovies="No internet service",
        Contract="Two year", PaperlessBilling="No", PaymentMethod="Bank transfer (automatic)",
        MonthlyCharges=25.0),
}


def examples_markdown(service) -> str:
    rows = []
    for label, profile in EXAMPLE_PROFILES.items():
        X = pd.DataFrame([{**profile, "TotalCharges": round(profile["tenure"] * profile["MonthlyCharges"], 2)}])
        scored = service.score(X).iloc[0]
        reasons = service.explain(X, top_k=3)["reasons"]
        why = "; ".join(f"{r['feature']} = {r['value']} ({'raises' if r['shap_log_odds'] > 0 else 'lowers'})"
                        for r in reasons)
        rows.append([label, f"{scored['churn_probability']:.1%}", scored["risk_band"],
                     "yes" if scored["predicted_churn"] else "no", why])
    return ("_Two illustrative customer profiles (made up for demonstration, not real people), "
            "scored by the saved model. Probabilities are estimates, not certainties._\n\n"
            + md_table(["Profile", "Churn probability", "Risk band", "Flagged?", "Top factors"], rows))


def main() -> None:
    from src.models.service import ChurnService
    if not README.exists():
        raise SystemExit(f"{README} not found. Create README.md first (with the result markers).")
    if not METRICS_PATH.exists():
        raise SystemExit("artifacts/metrics.json not found. Run: python -m src.models.train")
    metrics = json.loads(METRICS_PATH.read_text())
    meta = json.loads(METADATA_PATH.read_text())
    imp_path = REPORTS_DIR / "feature_importance.csv"
    importance = pd.read_csv(imp_path, index_col=0) if imp_path.exists() else None

    text = README.read_text(encoding="utf-8")
    text = replace_block(text, "RESULTS", results_markdown(metrics, meta, importance))
    text = replace_block(text, "EXAMPLES", examples_markdown(ChurnService.load()))
    README.write_text(text, encoding="utf-8")
    print(f"Updated {README} on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC")


if __name__ == "__main__":
    main()
